PROMPT === TABLAS USUARIO/ADMIN/ENCUESTADOR ===
SELECT TABLE_NAME FROM USER_TABLES
WHERE UPPER(TABLE_NAME) LIKE '%USUARIO%'
   OR UPPER(TABLE_NAME) LIKE '%ADMIN%'
   OR UPPER(TABLE_NAME) LIKE '%ENCUEST%'
   OR UPPER(TABLE_NAME) LIKE '%CIUDAD%'
ORDER BY 1;

PROMPT === COLUMNAS ===
SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE, NULLABLE
FROM USER_TAB_COLUMNS
WHERE TABLE_NAME IN (
  SELECT TABLE_NAME FROM USER_TABLES
  WHERE UPPER(TABLE_NAME) LIKE '%USUARIO%'
     OR UPPER(TABLE_NAME) LIKE '%ADMIN%'
     OR UPPER(TABLE_NAME) LIKE '%ENCUEST%'
)
ORDER BY TABLE_NAME, COLUMN_ID;

