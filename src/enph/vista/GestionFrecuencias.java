    private void Btn_EliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Btn_EliminarActionPerformed
        // TODO add your handling code here:
int fila = Tbl_Frecuencias.getSelectedRow();

    if (fila == -1) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Selecciona la frecuencia que deseas eliminar.",
            "Aviso",
            javax.swing.JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    int indice = Tbl_Frecuencias.convertRowIndexToModel(fila);

    enph.modelo.ItemCatalogo seleccionada =
        frecuenciasEnTabla.get(indice);

    enph.modelo.CatalogoDAO dao = new enph.modelo.CatalogoDAO();

    // No permitir eliminar frecuencias utilizadas en respuestas.
    if (dao.frecuenciaEnUso(seleccionada.getId())) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "No puedes eliminar esta frecuencia porque está siendo "
            + "utilizada en respuestas de la encuesta.",
            "Frecuencia en uso",
            javax.swing.JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    int confirmacion = javax.swing.JOptionPane.showConfirmDialog(
        this,
        "¿Estás seguro de eliminar la frecuencia \""
        + seleccionada.getNombre() + "\"?",
        "Confirmar eliminación",
        javax.swing.JOptionPane.YES_NO_OPTION,
        javax.swing.JOptionPane.WARNING_MESSAGE
    );

    if (confirmacion != javax.swing.JOptionPane.YES_OPTION) {
        return;
    }

    if (dao.eliminarFrecuencia(seleccionada.getId())) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "La frecuencia se eliminó correctamente.",
            "Éxito",
            javax.swing.JOptionPane.INFORMATION_MESSAGE
        );

        cargarFrecuencias();
    } else {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "No fue posible eliminar la frecuencia.",
            "Error",
            javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }
    }//GEN-LAST:event_Btn_EliminarActionPerformed

    private void Btn_CrearActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Btn_CrearActionPerformed
        // TODO add your handling code here:
    String nombre = javax.swing.JOptionPane.showInputDialog(
        this,
        "Nombre de la nueva frecuencia de compra:",
        "Crear frecuencia",
        javax.swing.JOptionPane.QUESTION_MESSAGE
    );

    // Si se cancela, no se hace nada.
    if (nombre == null) {
        return;
    }

    nombre = nombre.trim();

    // Validar que el nombre no esté vacío.
    if (nombre.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Debes ingresar el nombre de la frecuencia.",
            "Campo obligatorio",
            javax.swing.JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    enph.modelo.CatalogoDAO dao = new enph.modelo.CatalogoDAO();

    if (dao.crearFrecuencia(nombre)) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "La frecuencia se creó correctamente.",
            "Éxito",
            javax.swing.JOptionPane.INFORMATION_MESSAGE
        );

        cargarFrecuencias();
    } else {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "No fue posible crear la frecuencia.",
            "Error",
            javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }
    }//GEN-LAST:event_Btn_CrearActionPerformed

    private void Btn_EditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Btn_EditarActionPerformed
        // TODO add your handling code here:
    int fila = Tbl_Frecuencias.getSelectedRow();

    if (fila == -1) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Selecciona la frecuencia que deseas editar.",
            "Aviso",
            javax.swing.JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    // Convertir el índice por si la tabla utiliza ordenamiento.
    int indice = Tbl_Frecuencias.convertRowIndexToModel(fila);

    enph.modelo.ItemCatalogo seleccionada =
        frecuenciasEnTabla.get(indice);

    String nombre = javax.swing.JOptionPane.showInputDialog(
        this,
        "Ingresa el nuevo nombre de la frecuencia:",
        seleccionada.getNombre()
    );

    // Si se cancela, no se modifica nada.
    if (nombre == null) {
        return;
    }

    nombre = nombre.trim();

    if (nombre.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "El nombre de la frecuencia no puede estar vacío.",
            "Campo obligatorio",
            javax.swing.JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    enph.modelo.CatalogoDAO dao = new enph.modelo.CatalogoDAO();

    if (dao.editarFrecuencia(seleccionada.getId(), nombre)) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "La frecuencia se actualizó correctamente.",
            "Éxito",
            javax.swing.JOptionPane.INFORMATION_MESSAGE
        );

        cargarFrecuencias();
    } else {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "No fue posible actualizar la frecuencia.",
            "Error",
            javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }
    }//GEN-LAST:event_Btn_EditarActionPerformed

