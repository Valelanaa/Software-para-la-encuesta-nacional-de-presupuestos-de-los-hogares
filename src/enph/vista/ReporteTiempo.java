    private void configurarTabla() {

        DefaultTableModel modelo = new DefaultTableModel(new Object[]{"Encuestador", "Tiempo promedio"}, 0) {
            @Override
            public boolean isCellEditable(int fila, int columna) {
                return false;
            }
        };

        Tbl_Reporte.setModel(modelo);

        ajustarColumnas(Tbl_Reporte);
    }
    
    public void mostrarReporte(List<ReporteTiempoDTO> lista) {

        this.listaReportes = lista;

        DefaultTableModel modelo =
                (DefaultTableModel) Tbl_Reporte.getModel();

        modelo.setRowCount(0);

        for (ReporteTiempoDTO reporte : lista) {

            modelo.addRow(new Object[]{
                reporte.getNombreEncuestador(),
                reporte.getTiempoPromedioFormato()
            });
        }

        ajustarColumnas(Tbl_Reporte);
    }

// Ajusta el ancho de cada columna al contenido más largo: toma el mayor entre el título y todos los datos de la columna.
    private void ajustarColumnas(javax.swing.JTable tabla) {

        for (int col = 0; col < tabla.getColumnCount(); col++) {

            javax.swing.table.TableColumn columna =
                    tabla.getColumnModel().getColumn(col);

            // Ancho del título
            java.awt.Component comp = tabla.getTableHeader()
                    .getDefaultRenderer()
                    .getTableCellRendererComponent(
                            tabla,
                            columna.getHeaderValue(),
                            false,
                            false,
                            0,
                            col
                    );

            int ancho = comp.getPreferredSize().width;

            // Ancho del dato más largo
            for (int fila = 0; fila < tabla.getRowCount(); fila++) {

                comp = tabla.prepareRenderer(
                        tabla.getCellRenderer(fila, col),
                        fila,
                        col
                );

                ancho = Math.max(
                        ancho,
                        comp.getPreferredSize().width
                );
            }

            columna.setPreferredWidth(ancho + 20);
        }
    }

