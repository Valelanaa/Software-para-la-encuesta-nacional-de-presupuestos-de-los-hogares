// Ciudades del combo, en el mismo orden que sus opciones (para saber el id elegido)
private final java.util.List<enph.modelo.ItemCiudad> ciudades = new java.util.ArrayList<>();
// Usuario que se está editando (con los datos que había antes de guardar)
private enph.modelo.Usuario usuarioEditado;

public EditarUsuario() {
    this(null);   // para poder abrir la ventana sola desde el diseñador
}

public EditarUsuario(String idUsuario) {
    initComponents();

    // Datos de quien inició sesión (banner de la ventana)
    Lbl__Usuario1.setText(enph.modelo.SesionUsuario.nombreParaMostrar());
    Lbl_Rol1.setText(enph.modelo.SesionUsuario.rolParaMostrar());

    cargarCiudades();
    if (idUsuario != null) {
        cargarUsuario(idUsuario);
    }

    setLocationRelativeTo(null);// centra la ventana en la pantalla
}

// Llena el combo de ciudades desde la base de datos
private void cargarCiudades() {
    ciudades.clear();
    ciudades.addAll(new enph.modelo.UsuarioDAO().listarCiudades());
    Cmb_Ciudad.removeAllItems();
    for (enph.modelo.ItemCiudad c : ciudades) {
        Cmb_Ciudad.addItem(c.getNombre());
    }
}

// Lee el usuario de la base y muestra sus datos en los campos
private void cargarUsuario(String idUsuario) {
    usuarioEditado = new enph.modelo.UsuarioDAO().buscarPorId(idUsuario);
    if (usuarioEditado == null) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "No se pudo cargar el usuario.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        return;
    }
    Txt_Nombre.setText(usuarioEditado.getNombreCompleto());
    Txt_Cedula.setText(usuarioEditado.getDocumentoIdentidad());
    Txt_Telefono.setText(usuarioEditado.getTelefono());
    Txt_Contrasenna.setText(usuarioEditado.getContrasenna());
    Cmb_Rol.setSelectedItem(usuarioEditado.getRol());

    // Selecciona en el combo la ciudad que tiene registrada
    for (int i = 0; i < ciudades.size(); i++) {
        if (ciudades.get(i).getId().equals(usuarioEditado.getIdCiudad())) {
            Cmb_Ciudad.setSelectedIndex(i);
            break;
        }
    }
}
