    private void Btn_CrearActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Btn_CrearActionPerformed
        // TODO add your handling code here:
         int fila = Tbl_Frecuencias.getSelectedRow();

        if (fila == -1) {
            javax.swing.JOptionPane.showMessageDialog(
                this,
                "Selecciona una familia para ver los detalles de su encuesta.",
                "Seleccionar familia",
                javax.swing.JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        // Índice correcto aunque la tabla esté ordenada o filtrada.
        int indice = Tbl_Frecuencias.convertRowIndexToModel(fila);
        String idHogar = filasEnTabla.get(indice)[2];

        new VerDetallesEncuesta(idHogar, idEncuestador, nombreEncuestador)
                .setVisible(true);
        dispose();
    }//GEN-LAST:event_Btn_CrearActionPerformed

