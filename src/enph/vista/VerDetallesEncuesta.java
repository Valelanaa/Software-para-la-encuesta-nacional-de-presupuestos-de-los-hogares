    // Muestra los datos de la familia y las fechas de su encuesta.
    private void cargarDatos(String idHogar) {

        // Valores iniciales por si no hay datos.
        Lbl_NombreRta.setText("Sin información");
        Lbl_DireccionRta.setText("Sin información");
        Lbl_BarrioRta.setText("Sin información");
        Lbl_CiudadRta.setText("Sin información");
        Lbl_FechaInicioRta.setText("Sin realizar");
        Lbl_FechaFinRta.setText("Sin realizar");

        if (idHogar == null || idHogar.trim().isEmpty()) {
            return;
        }

        try {
            String[] d = new enph.modelo.HogarDAO().buscarDetalleEncuesta(idHogar);

            if (d == null) {
                javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "No se encontró la familia seleccionada.",
                    "Sin información",
                    javax.swing.JOptionPane.INFORMATION_MESSAGE
                );
                return;
            }

            Lbl_NombreRta.setText(textoVisible(d[0]));
            Lbl_DireccionRta.setText(textoVisible(d[1]));
            Lbl_BarrioRta.setText(textoVisible(d[2]));
            Lbl_CiudadRta.setText(textoVisible(d[3]));

            // Si no hay encuesta, las fechas llegan null y se queda "Sin realizar".
            if (d[4] != null) Lbl_FechaInicioRta.setText(d[4]);
            if (d[5] != null) Lbl_FechaFinRta.setText(d[5]);

        } catch (java.sql.SQLException ex) {
            javax.swing.JOptionPane.showMessageDialog(
                this,
                "No se pudieron consultar los datos:\n" + ex.getMessage(),
                "Error de base de datos",
                javax.swing.JOptionPane.ERROR_MESSAGE
            );
        }
    }

// Evita mostrar valores nulos o cadenas vacías en los labels.
private String textoVisible(String valor) {
    if (valor == null || valor.trim().isEmpty()) {
        return "Sin información";
    }

    return valor.trim();
}


