public VerCabezaHogar(String idHogar) {
    initComponents();

    // Mostrar los datos del usuario que inició sesión.
    Lbl__Usuario1.setText(
            enph.modelo.SesionUsuario.nombreParaMostrar()
    );

    Lbl_Rol1.setText(
            enph.modelo.SesionUsuario.rolParaMostrar()
    );

    // Consultar y mostrar la cabeza de hogar seleccionada.
    cargarCabezaHogar(idHogar);

    setLocationRelativeTo(null);
}


private void cargarCabezaHogar(String idHogar) {

    // Valores iniciales mientras se realiza la consulta.
    Lbl_NombreRta.setText("Sin información");
    Lbl_DocumentoRta.setText("Sin información");
    Lbl_CorreoRta.setText("Sin información");
    Lbl_TelefonoRta.setText("Sin información");

    // Si no se recibió un identificador, no se puede consultar.
    if (idHogar == null || idHogar.trim().isEmpty()) {
        return;
    }

    // Consultar la cabeza de hogar asociada al hogar seleccionado.
    enph.modelo.CabezaHogarDAO dao =
            new enph.modelo.CabezaHogarDAO();

    enph.modelo.CabezaHogar cabeza =
            dao.buscarPorHogar(idHogar);

    // Si existe un registro, mostrar sus datos.
    if (cabeza != null) {

        Lbl_NombreRta.setText(
                textoVisible(cabeza.getNombreCompleto())
        );

        Lbl_DocumentoRta.setText(
                textoVisible(cabeza.getDocumentoIdentidad())
        );

        Lbl_CorreoRta.setText(
                textoVisible(cabeza.getCorreo())
        );

        Lbl_TelefonoRta.setText(
                textoVisible(cabeza.getTelefono())
        );

    } else {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "No se encontró una cabeza de hogar registrada "
                + "para la familia seleccionada.",
                "Sin información",
                javax.swing.JOptionPane.INFORMATION_MESSAGE
        );
    }
}

// Evita mostrar valores nulos o cadenas vacías en los labels.
private String textoVisible(String valor) {
    if (valor == null || valor.trim().isEmpty()) {
        return "Sin información";
    }

    return valor.trim();
}


